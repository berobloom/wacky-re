#!/usr/bin/env python3
"""gensyms.py: the linker script that puts src/ww.c's externs where the game had them.

usage: port/tools/gensyms.py UNDEF DEFINED SYMMAP CPUBLICS SRC > port/gen/syms.ld

UNDEF/DEFINED: `nm -u` / defined names of the port's ww.o. SYMMAP: .work/link/symmap.txt (the game
address of every external of our Watcom object). CPUBLICS: .work/link/cpublics.txt (our Watcom
publics -> game address). Data names become `name = 0xADDR;` (the data object is mapped at its game
address, port/src/image.c). A name for one of our own C functions (a `#pragma aux` alias or an old
hex name) becomes `name = ourfunction;`, found by game address. asm and library names are left to
the runtime; the script lists them in a comment so a missing one is visible.
Regenerate after src/ww.c gains or renames an extern (needs the Watcom build: tools/link/build.sh).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import classify  # noqa: E402


# names whose Watcom convention a plain alias cannot reproduce: port/src/glue.c defines them
GLUE = {'showlines'}          # value [ecx]: returns the caller's 4th argument (ECX preserved)


def main(undef, defined, symmap, cpublics, src):
    text = open(src, encoding='latin-1').read()
    alias = dict(re.findall(r'#pragma aux (\w+)\s+"(\w+)"', text))
    ours = set(l.strip() for l in open(defined))
    watcom_of = {d: alias.get(d, d + '_') for d in ours}         # our gcc name -> Watcom public
    addr_of = {}
    for line in open(cpublics):
        f = line.split()
        if len(f) >= 2:
            addr_of[f[0]] = int(f[1], 16)
    by_addr = {}
    for d, w in watcom_of.items():
        if w in addr_of:
            by_addr.setdefault(addr_of[w], d)
    out, left = ['/* generated by port/tools/gensyms.py - do not edit */'], []
    for u, a, k, sym in classify.load(undef, symmap, src):
        if u in GLUE:
            left.append('%s(glue)' % u)
            continue
        if k == 'data':
            out.append('%s = 0x%06x;' % (u, a))
        elif k == 'C':
            t = by_addr.get(a)
            if t is None:
                left.append('%s(C %06x: no function of ours there)' % (u, a))
            elif t != u:
                out.append('%s = %s;' % (u, t))
        else:
            left.append('%s(%s)' % (u, k))
    out.append('/* left to the runtime: %s */' % ' '.join(sorted(left)))
    print('\n'.join(out))


if __name__ == '__main__':
    main(*sys.argv[1:6])
