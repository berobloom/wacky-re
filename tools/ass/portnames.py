#!/usr/bin/env python3
"""portnames.py: name, in analysis/ww_names.txt, every function and variable of the ASS modules that
build byte-identical to the game as a whole.

usage: tools/ass/portnames.py MODULE[:BASE] ...      (after tools/ass/build.sh)

For each module, places .work/ass/19941101/MODULE.OBJ's _TEXT (at BASE, hex, or by its first public that
tools/wc/objmatch.py MATCHes), checks that the whole segment equals WW.EXE (fixups masked; refuses
otherwise), and collects the module's own symbols: its publics, and the fixup targets objmatch resolves
(statics included) that fall inside one of the module's segments as placed. Those lines go into the
"# ---- ASS port (" block as CONFIRMED; a line the block already has for an address is replaced, other
lines for the same addresses elsewhere in the file are dropped (the ASSMATCH block is regenerated by
tools/wc/assmatch.py --write, which skips the port block's addresses)."""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'wc'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'le'))
import libmatch as L  # noqa: E402
import objmatch  # noqa: E402
from lelib import Image  # noqa: E402

NAMES = os.path.join(ROOT, 'analysis', 'ww_names.txt')
HEAD, END = '# ---- ASS port (', '# ---- ASS port end'


def seg_sizes(recs):
    """{segment name: length} from the SEGDEF records (the BSS has no data records to measure)"""
    lnames, out = [None], {}
    for t, b in recs:
        if t == 0x96:
            p = 0
            while p < len(b):
                lnames.append(b[p + 1:p + 1 + b[p]].decode('latin1'))
                p += 1 + b[p]
        elif t in (0x98, 0x99):
            p0 = 1 + (3 if b[0] >> 5 == 0 else 0)
            for lsize in ((4, 2) if t == 0x99 else (2, 4)):   # as libmatch.code_of: Watcom writes some 0x98 with 4
                ln, p = L.index(b, p0 + lsize)
                cl, p = L.index(b, p)
                if 0 < ln < len(lnames) and 0 < cl < len(lnames) and p + 1 == len(b):
                    break
            out[lnames[ln]] = int.from_bytes(b[p0:p0 + lsize], 'little')
    return out


def module_names(mod, base, img):
    obj = os.path.join(ROOT, '.work', 'ass', '19941101', mod + '.OBJ')
    recs = [r for _, r in L.modules(open(obj, 'rb').read())][0]
    segs = L.code_of(recs)
    out = subprocess.run([sys.executable, 'tools/wc/objmatch.py', 'ww', obj], cwd=ROOT, capture_output=True, text=True).stdout
    pubs = [(s, o, n) for s, o, n in objmatch.publics(recs)]
    if base is None:
        offs = {n: o for s, o, n in pubs if s == '_TEXT'}
        for m in re.finditer(r'^(\S+)\s+\d+ bytes\s+MATCH at 0x([0-9a-f]+)', out, re.M):
            if m.group(1) in offs:
                base = int(m.group(2), 16) - offs[m.group(1)]
                break
    if base is None:
        sys.exit('%s: no MATCHed public to place it by; give MODULE:BASE' % mod)
    buf, mask = segs['_TEXT']
    g = img.code[base - img.code_base:base - img.code_base + len(buf)]
    d = sum(1 for i in range(len(buf)) if not mask[i] and buf[i] != g[i])
    if d:
        sys.exit('%s: _TEXT at 0x%05X has %d differing bytes: not a whole-module match' % (mod, base, d))
    # where objmatch placed each segment; sizes from the object
    where = {'_TEXT': base}
    for m in re.finditer(r'^  segment (\S+)\s+base 0x([0-9a-f]+)', out, re.M):
        where[m.group(1)] = int(m.group(2), 16)
    sizes = seg_sizes(recs)
    ranges = [(where[s], where[s] + sizes.get(s, 0)) for s in where if sizes.get(s)]
    res = {}
    for s, o, n in pubs:
        if s in where:
            res[where[s] + o] = n.strip('_') if s == '_TEXT' else n.lstrip('_')
    # every named fixup target, resolved from the game's bytes at the fixup (the whole _TEXT is placed)
    for seg, at, loc, selfrel, kind, nm, disp in L.fixups_of(recs):
        if loc != 9 or seg != '_TEXT' or kind == 'seg' or not nm:
            continue
        if not selfrel:                                    # Watcom keeps the addend in the data bytes
            disp += int.from_bytes(bytes(buf[at:at + 4]), 'little', signed=True)
        v = img.u32(base + at)
        a = ((base + at + 4 + v) & 0xFFFFFFFF if selfrel else v) - disp
        if any(lo <= a < hi for lo, hi in ranges):
            res.setdefault(a, nm.strip('_') if a < img.data_base else nm.lstrip('_'))
    return base, len(buf), {a: n.rstrip('_') for a, n in res.items()}


def main(argv):
    if not argv:
        sys.exit(__doc__)
    img = Image('ww')
    new = {}
    for arg in argv:
        mod, _, b = arg.upper().partition(':')
        base, size, names = module_names(mod, int(b, 16) if b else None, img)
        why = 'src/ass %s.C builds byte-identical to the whole module 0x%05X-0x%05X' % (mod, base, base + size)
        for a, n in names.items():
            new[a] = '0x%06x %-24s # CONFIRMED: %s' % (a, n, why)
        print('%s: %d names (_TEXT 0x%05X, %d bytes)' % (mod, len(names), base, size))
    lines = open(NAMES).read().split('\n')
    h = next(i for i, l in enumerate(lines) if l.startswith(HEAD))
    e = next(i for i, l in enumerate(lines) if l.startswith(END))
    block = {}
    for l in lines[h + 1:e]:
        m = re.match(r'^0x([0-9a-f]+) ', l)
        if m:
            block[int(m.group(1), 16)] = l
    for a, l in new.items():
        old = block.get(a)
        if old and old.split()[1] == l.split()[1] and 'CONFIRMED' in old:
            continue                     # keep a hand-written line that says more
        block[a] = l
    keep = lambda l: not (re.match(r'^0x([0-9a-f]+) ', l) and int(l.split()[0], 16) in new)  # noqa: E731
    out = [l for l in lines[:h + 1] if keep(l)] + [block[a] for a in sorted(block)] + [l for l in lines[e:] if keep(l)]
    open(NAMES, 'w').write('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
